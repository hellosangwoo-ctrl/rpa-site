function hreflangBlock(self) {
  const lines = [`<link rel="canonical" href="${cfg.site}${self.path}">`];
  for (const l of LOCALES) lines.push(`<link rel="alternate" hreflang="${l.htmlLang}" href="${cfg.site}${l.path}">`);
  lines.push(`<link rel="alternate" hreflang="x-default" href="${cfg.site}${byCode[cfg.defaultLocale].path}">`);
  return lines.join('\n');
}

/* Language routing. The apex (default locale) reads the visitor's browser
   languages and forwards them once; every other locale is an explicit URL and
   never bounces a visitor off it. A choice made in the picker always wins and
   is remembered. Set AUTO to false on the apex to switch detection off. */
function routingScript(self) {
  const table = LOCALES.map(l => `{c:'${l.code}',p:'${l.path}',m:${JSON.stringify(l.match)}}`).join(',');
  const auto = self.code === cfg.defaultLocale;
  return `<script>
/* Language routing — generated by _i18n/build.mjs, do not edit by hand.
   AUTO=true only on the apex page: it forwards a first-time visitor to the
   page matching their browser language. Set it to false to turn detection off;
   the language picker and hreflang keep working either way. */
(function(){
  var AUTO = ${auto};
  var HERE = '${self.code}';
  var L = [${table}];
  var FALLBACK = '${FALLBACK.code}';
  var KEY = 'rpaLang', ONCE = 'rpaAuto';
  function pathOf(c){ for(var i=0;i<L.length;i++) if(L[i].c===c) return L[i].p; return null; }
  function known(c){ return !!pathOf(c); }
  try{
    var store=null; try{ store=window.localStorage; store.getItem(KEY); }catch(e){ store=null; }
    var forced=(location.search.match(/[?&]lang=([a-z]{2})\\b/)||[])[1]||null;
    var want=null;
    if(forced && known(forced)){
      want=forced;
      if(store){ store.setItem(KEY,want); store.setItem(ONCE,'1'); }
      if(history.replaceState) history.replaceState(null,'',location.pathname+location.hash);
    } else {
      var saved=store&&store.getItem(KEY);
      if(saved && known(saved)){ want=saved; }
      else if(AUTO && !(store&&store.getItem(ONCE))){
        var langs=navigator.languages&&navigator.languages.length?navigator.languages:[navigator.language||''];
        outer: for(var i=0;i<langs.length;i++){
          var tag=(langs[i]||'').toLowerCase();
          for(var j=0;j<L.length;j++) for(var k=0;k<L[j].m.length;k++){
            var m=L[j].m[k];
            if(tag===m||tag.indexOf(m+'-')===0){ want=L[j].c; break outer; }
          }
        }
        if(!want) want=FALLBACK;
        if(store) store.setItem(ONCE,'1');
      }
    }
    if(AUTO && want && want!==HERE) location.replace(pathOf(want));
  }catch(e){}
})();
</script>`;
}

function switcher(self) {
  const opts = LOCALES.map(l =>
    `<option value="${l.path}?lang=${l.code}"${l.code === self.code ? ' selected' : ''} lang="${l.htmlLang}">${esc(l.native)}</option>`
  ).join('');
  return `<span class="lang"><span class="globe" aria-hidden="true">🌐</span><select id="langPick" aria-label="Language">${opts}</select></span>`;
}

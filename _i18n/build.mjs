/* ── the hand-written Korean page: only the marked blocks are rewritten ── */
function patchHandwritten(loc) {
  const p = join(ROOT, loc.file);
  let s = readFileSync(p, 'utf8');
  const blocks = {
    head: hreflangBlock(loc) + '\n' + SWITCHER_CSS + '\n' + routingScript(loc),
    switcher: switcher(loc) + SWITCHER_JS,
    footerlangs: footerLangs(loc)
  };
  for (const [name, body] of Object.entries(blocks)) {
    const re = new RegExp(`(<!--i18n:${name}-->)[\\s\\S]*?(<!--/i18n:${name}-->)`);
    if (!re.test(s)) throw new Error(`${loc.file}: missing <!--i18n:${name}--> … <!--/i18n:${name}--> markers`);
    s = s.replace(re, `$1\n${body}\n$2`);
  }
  return { path: p, out: s };
}

/* lastmod only moves for a page whose HTML actually changed in this build —
   otherwise the previous value is carried over, so re-running the build on a
   later day is a no-op rather than a diff. */
function previousLastmods() {
  const out = {};
  try {
    const xml = readFileSync(join(ROOT, 'sitemap.xml'), 'utf8');
    for (const m of xml.matchAll(/<loc>([^<]+)<\/loc>[\s\S]*?<lastmod>([\d-]+)<\/lastmod>/g)) {
      const path = m[1].replace(cfg.site, '');
      const loc = LOCALES.find(l => l.path === path);
      if (loc) out[loc.code] = m[2];
    }
  } catch { /* no sitemap yet */ }
  return out;
}

function sitemap(lastmods) {
  const alt = LOCALES.map(l => `    <xhtml:link rel="alternate" hreflang="${l.htmlLang}" href="${cfg.site}${l.path}"/>`).join('\n')
    + `\n    <xhtml:link rel="alternate" hreflang="x-default" href="${cfg.site}${byCode[cfg.defaultLocale].path}"/>`;
  const today = new Date().toISOString().slice(0, 10);
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${LOCALES.map((l, i) => `  <url><loc>${cfg.site}${l.path}</loc>
${alt}
    <lastmod>${lastmods[l.code] || today}</lastmod><changefreq>monthly</changefreq><priority>${i === 0 ? '1.0' : '0.9'}</priority></url>`).join('\n')}
</urlset>
`;
}

/* ── run ────────────────────────────────────────────────────────────── */
const writes = [];
for (const loc of LOCALES) {
  if (loc.source === 'handwritten') { writes.push(patchHandwritten(loc)); continue; }
  const cPath = join(HERE, 'content', `${loc.code}.json`);
  if (!existsSync(cPath)) { console.error(`  skip ${loc.code}: no content/${loc.code}.json`); continue; }
  writes.push({ path: join(ROOT, loc.file), out: buildPage(loc, JSON.parse(readFileSync(cPath, 'utf8'))) });
}
/* decide each page's lastmod before the sitemap is built */
const prev = previousLastmods();
const today = new Date().toISOString().slice(0, 10);
const lastmods = {};
for (const loc of LOCALES) {
  const w = writes.find(x => x.path === join(ROOT, loc.file));
  const before = w && existsSync(w.path) ? readFileSync(w.path, 'utf8') : null;
  lastmods[loc.code] = (w && before === w.out && prev[loc.code]) ? prev[loc.code] : today;
}
writes.push({ path: join(ROOT, 'sitemap.xml'), out: sitemap(lastmods) });

let changed = 0;
for (const w of writes) {
  const before = existsSync(w.path) ? readFileSync(w.path, 'utf8') : null;
  const same = before === w.out;
  if (!same) changed++;
  if (!CHECK && !same) { mkdirSync(dirname(w.path), { recursive: true }); writeFileSync(w.path, w.out); }
  console.log(`  ${same ? 'same  ' : CHECK ? 'DIFF  ' : 'write '} ${w.path.replace(ROOT + '/', '')}  (${w.out.length.toLocaleString()} bytes)`);
}
console.log(CHECK ? `\n${changed} file(s) would change.` : `\n${changed} file(s) written, ${writes.length - changed} unchanged.`);
